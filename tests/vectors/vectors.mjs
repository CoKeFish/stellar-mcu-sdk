// Reference vectors made with the official JavaScript SDK (@stellar/stellar-sdk).
// The test in tests/host builds the same things with the C core and compares byte by byte.
// Usage, in a folder where the JavaScript SDK is installed:
//   npm install @stellar/stellar-sdk
//   node vectors.mjs [output file]      (by default, vectors.h next to this file)
import fs from 'node:fs';
import * as S from '@stellar/stellar-sdk';

const { Keypair, Networks, TransactionBuilder, Operation, Asset, Account, Memo, xdr, Address,
  nativeToScVal, hash, StrKey, SorobanDataBuilder } = S;

const OUTPUT = process.argv[2] ?? new URL('./vectors.h', import.meta.url);
const NETWORK = Networks.TESTNET;
const USDC_TESTNET = 'GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5';
const USDC_MAINNET = 'GA5ZSEJYB37JRC5AVCIA5MOP4RHTM335X2KGX3IHOJAPP5RE34K4KZVN';

// Fixed keys only for the vectors (they are not used on the network).
const A = Keypair.fromRawEd25519Seed(Buffer.from(Array.from({ length: 32 }, (_, i) => i + 1)));
const B = Keypair.fromRawEd25519Seed(Buffer.from(Array.from({ length: 32 }, (_, i) => i + 0x21)));
const timebounds = { minTime: 0, maxTime: 1800000000 };
const account = () => new Account(A.publicKey(), '123456788');

// 1. Classic XLM payment with a numeric memo.
const tx1 = new TransactionBuilder(account(), { fee: '100', networkPassphrase: NETWORK, timebounds })
  .addOperation(Operation.payment({ destination: B.publicKey(), asset: Asset.native(), amount: '1.2345678' }))
  .addMemo(Memo.id('4242'))
  .build();
tx1.sign(A);

// 2. Classic USDC payment, no memo.
const tx2 = new TransactionBuilder(account(), { fee: '100', networkPassphrase: NETWORK, timebounds })
  .addOperation(Operation.payment({ destination: B.publicKey(), asset: new Asset('USDC', USDC_TESTNET), amount: '2.5' }))
  .build();
tx2.sign(A);

// 3. Call to the token contract: transfer(from, to, amount), authorized by the source account.
const nativeContract = Asset.native().contractId(NETWORK);
const args = [
  new Address(A.publicKey()).toScVal(),
  new Address(B.publicKey()).toScVal(),
  nativeToScVal(5000000n, { type: 'i128' }),
];
const call = new xdr.InvokeContractArgs({
  contractAddress: new Address(nativeContract).toScAddress(),
  functionName: 'transfer',
  args,
});
const authorization = new xdr.SorobanAuthorizationEntry({
  credentials: xdr.SorobanCredentials.sorobanCredentialsSourceAccount(),
  rootInvocation: new xdr.SorobanAuthorizedInvocation({
    function: xdr.SorobanAuthorizedFunction.sorobanAuthorizedFunctionTypeContractFn(call),
    subInvocations: [],
  }),
});
const sorobanData = new SorobanDataBuilder().setResourceFee(12345).setResources(100000, 200, 300).build();
const tx3 = new TransactionBuilder(account(), { fee: '100', networkPassphrase: NETWORK, timebounds })
  .addOperation(Operation.invokeHostFunction({
    func: xdr.HostFunction.hostFunctionTypeInvokeContract(call),
    auth: [authorization],
  }))
  .setSorobanData(sorobanData)
  .build();
tx3.sign(A);

// The same call with no authorization and no resource data: this is what is sent to be simulated.
const tx3sim = new TransactionBuilder(account(), { fee: '100', networkPassphrase: NETWORK, timebounds })
  .addOperation(Operation.invokeHostFunction({
    func: xdr.HostFunction.hostFunctionTypeInvokeContract(call),
    auth: [],
  }))
  .build();

// Event values: the two formats SEP-41 allows for "transfer".
const eventInt = nativeToScVal(5000000n, { type: 'i128' }).toXDR('base64');
const eventMap = xdr.ScVal.scvMap([
  new xdr.ScMapEntry({ key: xdr.ScVal.scvSymbol('amount'), val: nativeToScVal(12345678n, { type: 'i128' }) }),
  new xdr.ScMapEntry({ key: xdr.ScVal.scvSymbol('to_muxed_id'), val: xdr.ScVal.scvU64(4242n) }),
]).toXDR('base64');

const bytes = (b) => '{' + Array.from(b).map((x) => '0x' + x.toString(16).padStart(2, '0')).join(',') + '}';
const text = (s) => JSON.stringify(s);
const lines = [
  '// Generated by tests/vectors/vectors.mjs with @stellar/stellar-sdk. Do not edit.',
  '#pragma once',
  '#include <stdint.h>',
  `static const char V_NETWORK[] = ${text(NETWORK)};`,
  `static const uint8_t V_NETWORK_ID[32] = ${bytes(hash(Buffer.from(NETWORK)))};`,
  `static const uint8_t V_SEED_A[32] = ${bytes(A.rawSecretKey())};`,
  `static const uint8_t V_PUB_A[32] = ${bytes(A.rawPublicKey())};`,
  `static const uint8_t V_PUB_B[32] = ${bytes(B.rawPublicKey())};`,
  `static const char V_ACCOUNT_A[] = ${text(A.publicKey())};`,
  `static const char V_SECRET_A[] = ${text(A.secret())};`,
  `static const char V_ACCOUNT_B[] = ${text(B.publicKey())};`,
  `static const char V_USDC_ISSUER[] = ${text(USDC_TESTNET)};`,
  `static const char V_CONTRACT_NATIVE[] = ${text(nativeContract)};`,
  `static const char V_CONTRACT_USDC[] = ${text(new Asset('USDC', USDC_TESTNET).contractId(NETWORK))};`,
  `static const char V_TX1_HASH[] = ${text(Buffer.from(tx1.hash()).toString('hex'))};`,
  `static const char V_TX1_ENVELOPE[] = ${text(tx1.toEnvelope().toXDR('base64'))};`,
  `static const char V_TX2_ENVELOPE[] = ${text(tx2.toEnvelope().toXDR('base64'))};`,
  `static const char V_TX3_ENVELOPE[] = ${text(tx3.toEnvelope().toXDR('base64'))};`,
  `static const char V_TX3_SIM[] = ${text(tx3sim.toEnvelope().toXDR('base64'))};`,
  `static const uint32_t V_TX3_FEE = ${tx3.fee};`,
  `static const char V_SOROBAN_DATA[] = ${text(sorobanData.toXDR('base64'))};`,
  `static const char V_AUTH[] = ${text(authorization.toXDR('base64'))};`,
  `static const char V_TOPIC_TRANSFER[] = ${text(xdr.ScVal.scvSymbol('transfer').toXDR('base64'))};`,
  `static const char V_TOPIC_ACCOUNT_B[] = ${text(new Address(B.publicKey()).toScVal().toXDR('base64'))};`,
  `static const char V_ACCOUNT_KEY_A[] = ${text(xdr.LedgerKey.account(new xdr.LedgerKeyAccount({ accountId: A.xdrAccountId() })).toXDR('base64'))};`,
  `static const char V_EVENT_INT[] = ${text(eventInt)};`,
  `static const char V_EVENT_MAP[] = ${text(eventMap)};`,
  `static const char V_SEP7[] = ${text(`web+stellar:pay?destination=${B.publicKey()}&amount=2.5&asset_code=USDC&asset_issuer=${USDC_TESTNET}&memo=4242&memo_type=MEMO_ID`)};`,
  '',
];
fs.writeFileSync(OUTPUT, lines.join('\n'));

console.log('vectors written to', String(OUTPUT));
console.log('XLM contract testnet :', nativeContract);
console.log('USDC contract testnet:', new Asset('USDC', USDC_TESTNET).contractId(NETWORK));
